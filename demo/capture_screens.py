#!/usr/bin/env python3
"""Render deterministic SVG screenshots of PewwTerm with Textual's test driver.

Usage:
    python demo/capture_screens.py /path/to/media --output demo/screenshots

The previews are generated by the same helpers the application uses, so the
captures include real chafa/FFmpeg/Poppler output when those tools are present.
"""

from __future__ import annotations

import argparse
import asyncio
from pathlib import Path

from textual.widgets import DataTable, Input

from pewwterm.app import PewwTermApp
from pewwterm.models import FileKind


async def settle(app: PewwTermApp, pilot) -> None:
    await pilot.pause()
    try:
        await app.workers.wait_for_complete()
    except Exception:
        pass
    await pilot.pause()


def write_svg(app: PewwTermApp, directory: Path, name: str, title: str) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    path.write_text(app.export_screenshot(title=title), encoding="utf-8")
    print(f"wrote {path}")


async def capture_media(
    app: PewwTermApp, pilot, directory: Path, kind: FileKind | None
) -> None:
    if kind is None:
        return
    index = next(
        (
            index
            for index, record in enumerate(app._display_records)
            if record.kind is kind
        ),
        None,
    )
    if index is None:
        return
    names = {
        FileKind.IMAGE: "02-image.svg",
        FileKind.VIDEO: "03-video.svg",
        FileKind.PDF: "04-pdf.svg",
    }
    table = app.query_one("#files", DataTable)
    table.move_cursor(row=index, animate=False)
    await settle(app, pilot)
    write_svg(app, directory, names[kind], f"PewwTerm · {kind.value} preview")


async def capture(root: Path, output: Path) -> None:
    app = PewwTermApp(root)
    async with app.run_test(size=(120, 38)) as pilot:
        await settle(app, pilot)
        write_svg(app, output, "01-files.svg", "PewwTerm · file browser")
        for kind in (FileKind.IMAGE, FileKind.VIDEO, FileKind.PDF):
            await capture_media(app, pilot, output, kind)

        await pilot.press("slash")
        field = app.query_one("#search-input", Input)
        field.value = "a"
        await settle(app, pilot)
        write_svg(app, output, "05-search.svg", "PewwTerm · search")
        await pilot.press("escape", "escape")
        await pilot.pause(0.1)

        await pilot.press("question_mark")
        await pilot.pause(0.2)
        write_svg(app, output, "06-help.svg", "PewwTerm · keyboard help")

    narrow = PewwTermApp(root)
    async with narrow.run_test(size=(80, 24)) as pilot:
        await settle(narrow, pilot)
        write_svg(narrow, output, "07-narrow.svg", "PewwTerm · narrow layout")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="directory with sample media")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parent / "screenshots",
        help="directory for generated SVG files",
    )
    arguments = parser.parse_args()
    asyncio.run(capture(arguments.directory.expanduser().resolve(), arguments.output))


if __name__ == "__main__":
    main()
