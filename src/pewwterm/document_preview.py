"""Text, Markdown and PDF document previews.

Large files are bounded before they reach Textual: at most
``config.MAX_TEXT_BYTES`` are read and at most ``config.MAX_TEXT_LINES`` lines are
shown.  PDF text is extracted by Poppler's ``pdftotext`` (first pages only), and
an optional first-page thumbnail is generated by ``pdftoppm`` and then rendered
by :mod:`pewwterm.image_preview`.

PDF support requires Poppler utilities, not a Python PDF library.  When they are
missing the preview says so and still lists the file's basic metadata.  Binary
files are detected by a NUL byte and are never dumped as mojibake.
"""

from __future__ import annotations

import hashlib
import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import config


@dataclass(slots=True)
class TextDocument:
    """Decoded text plus truncation/error information."""

    text: str = ""
    truncated: bool = False
    error: str | None = None
    notice: str | None = None


@dataclass(slots=True)
class PdfThumbnail:
    path: Path | None = None
    error: str | None = None


def read_text_document(
    path: Path | str,
    *,
    max_bytes: int = config.MAX_TEXT_BYTES,
    max_lines: int = config.MAX_TEXT_LINES,
) -> TextDocument:
    """Read a bounded UTF-8 text preview.

    Decode failures are replaced rather than raised, but content that looks
    binary (NUL in the sampled prefix) is rejected with a friendly error.
    Permission errors and races produce an error instead of an exception.
    """

    candidate = Path(path)
    try:
        with candidate.open("rb") as handle:
            data = handle.read(max_bytes + 1)
    except PermissionError:
        return TextDocument(error="Permission denied while reading this file")
    except FileNotFoundError:
        return TextDocument(error="File no longer exists")
    except OSError as error:
        return TextDocument(error=f"Cannot read file: {error}")

    truncated = len(data) > max_bytes
    data = data[:max_bytes]
    if b"\x00" in data[: config.TEXT_SNIFF_BYTES]:
        return TextDocument(error="File appears to be binary; no text preview available")

    text = data.decode("utf-8", errors="replace")
    lines = text.splitlines()
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        truncated = True
    notice = "Preview truncated; open the file externally to read all of it." if truncated else None
    return TextDocument(text="\n".join(lines), truncated=truncated, notice=notice)


def pdf_text(
    path: Path | str,
    *,
    max_pages: int = config.MAX_PDF_PAGES,
    max_lines: int = config.MAX_TEXT_LINES,
) -> TextDocument:
    """Extract text from the first *max_pages* PDF pages with ``pdftotext``.

    ``-`` asks Poppler to write to stdout, so no temporary file is needed.  A
    non-zero exit (encrypted/corrupt PDF) is reported as an error.
    """

    candidate = Path(path)
    executable = config.which("pdftotext")
    if executable is None:
        return TextDocument(error="pdftotext not found; install poppler for PDF previews")
    command = [
        executable,
        "-layout",
        "-f",
        "1",
        "-l",
        str(max(1, max_pages)),
        "-enc",
        "UTF-8",
        str(candidate),
        "-",
    ]
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=config.SUBPROCESS_TIMEOUT,
            check=False,
        )
    except FileNotFoundError:
        return TextDocument(error="pdftotext disappeared from PATH")
    except subprocess.TimeoutExpired:
        return TextDocument(error="pdftotext timed out")
    except OSError as error:
        return TextDocument(error=f"pdftotext could not start: {error}")
    if completed.returncode != 0:
        detail = (completed.stderr or "").strip().splitlines()
        message = detail[-1] if detail else f"exit code {completed.returncode}"
        return TextDocument(error=f"PDF extraction failed: {message}")

    raw = completed.stdout.replace("\f", "\n")
    lines = raw.splitlines()
    truncated = False
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        truncated = True
    text = "\n".join(lines).strip()
    if not text:
        return TextDocument(
            text="",
            notice="No selectable text found (the PDF may be scanned images).",
        )
    notice = None
    if truncated:
        notice = "PDF text preview truncated; open the PDF to read the remaining pages."
    return TextDocument(text=text, truncated=truncated, notice=notice)


def _cache_key(path: Path) -> str:
    try:
        info = path.stat()
        identity = f"{path.resolve()}|{info.st_size}|{info.st_mtime_ns}"
    except OSError:
        identity = str(path)
    return hashlib.sha256(identity.encode("utf-8", "surrogatepass")).hexdigest()[:24]


def pdf_thumbnail(
    path: Path | str,
    *,
    cache_root: Path | str | None = None,
    scale_to: int = 900,
) -> PdfThumbnail:
    """Optionally render the first PDF page to a cached PNG.

    This is best-effort: failure does not prevent the text preview from being
    shown.  ``pdftoppm -singlefile`` writes ``prefix.png``; we generate into a
    temporary prefix and atomically move the result into the cache.
    """

    candidate = Path(path)
    executable = config.which("pdftoppm")
    if executable is None:
        return PdfThumbnail(error="pdftoppm not found; install poppler for PDF page previews")

    cache_base = Path(cache_root) if cache_root is not None else config.cache_dir()
    output_directory = cache_base / "pdf"
    try:
        output_directory.mkdir(parents=True, exist_ok=True)
    except OSError as error:
        return PdfThumbnail(error=f"Cannot create PDF cache: {error}")

    key = _cache_key(candidate)
    output_path = output_directory / f"{key}.png"
    if output_path.is_file() and output_path.stat().st_size > 0:
        return PdfThumbnail(path=output_path)

    temporary_prefix = output_directory / f"{key}.part"
    command = [
        executable,
        "-f",
        "1",
        "-l",
        "1",
        "-scale-to",
        str(max(200, scale_to)),
        "-png",
        "-singlefile",
        str(candidate),
        str(temporary_prefix),
    ]
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=config.SUBPROCESS_TIMEOUT,
            check=False,
        )
    except FileNotFoundError:
        return PdfThumbnail(error="pdftoppm disappeared from PATH")
    except subprocess.TimeoutExpired:
        return PdfThumbnail(error="pdftoppm timed out")
    except OSError as error:
        return PdfThumbnail(error=f"pdftoppm could not start: {error}")

    # pdftoppm -singlefile *appends* .png to the prefix (key.part -> key.part.png),
    # it does not replace the final suffix.
    generated = Path(f"{temporary_prefix}.png")
    if completed.returncode != 0 or not generated.is_file() or generated.stat().st_size == 0:
        detail = (completed.stderr or "").strip().splitlines()
        message = detail[-1] if detail else f"exit code {completed.returncode}"
        try:
            generated.unlink(missing_ok=True)
        except OSError:
            pass
        return PdfThumbnail(error=f"Cannot render PDF page: {message}")
    try:
        generated.replace(output_path)
    except OSError as error:
        return PdfThumbnail(error=f"Cannot store PDF thumbnail: {error}")
    return PdfThumbnail(path=output_path)
